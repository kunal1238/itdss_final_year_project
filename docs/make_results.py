"""python docs/make_results.py -> docs/RESULTS.md (generated from the model reports, never by hand)"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
f = lambda v, p=False: "–" if v is None else (f"{v:.1%}" if p else f"{v:g}")
out = ["# Out-of-sample results", "", "Generated by `docs/make_results.py`. Purged expanding walk-forward, 5 folds, after costs,",
       "1% equity risked per trade, at most 5 open trades. R = result as a multiple of the amount risked.", ""]
for tf in ("1h", "1d"):
    r = json.loads((root / f"backend/ml/report_{tf}.json").read_text())
    out += [f"## {tf} bars", "", f"Data {' to '.join(r['data'])}; test {' to '.join(r['oos'])}; {r['rows']:,} rows "
            f"({r['n_oos']:,} out-of-sample), {len(r['instruments'])} instruments. Class share: {r['class_share']}.",
            f"**Proven edge: {'yes' if r['edge_proven'] else 'no'}.**", "",
            "| Method | Accuracy | Balanced acc. | Macro precision | Macro recall | Log-loss | Trades | Win rate | Avg R | 95% CI | Profit factor | Sharpe | Max DD |",
            "|---|" + "---|" * 12]
    for k, v in r["results"].items():
        g = v.get
        out.append(f"| {k} | {f(g('accuracy'), 1)} | {f(g('balanced_accuracy'), 1)} | {f(g('precision'), 1)} | {f(g('recall'), 1)} | {f(g('log_loss'))} | "
                   f"{f(g('trades'))} | {f(g('win_rate'), 1)} | {f(g('avg_r'))} | {g('ci') or '–'} | {f(g('profit_factor'))} | {f(g('sharpe'))} | {f(g('max_drawdown'), 1)} |")
    out += ["", "Random Forest confusion matrix (rows actual, columns predicted; SELL, NEUTRAL, BUY): "
            f"`{r['results']['random_forest']['confusion']}`", "", f"Permutation importance (increase in log-loss): `{r['importance']}`", ""]
(root / "docs/RESULTS.md").write_text("\n".join(out))
